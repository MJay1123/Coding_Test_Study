WITH TRUCK_TABLE AS (SELECT
        CRCRH.HISTORY_ID,
        CRCC.CAR_ID,
        CRCC.CAR_TYPE,
        CRCC.DAILY_FEE,
        DATEDIFF(END_DATE, START_DATE) + 1 AS DURATION,
        CASE
            WHEN DATEDIFF(END_DATE, START_DATE) >= 90 THEN '90일 이상'
            WHEN DATEDIFF(END_DATE, START_DATE) >= 30 THEN '30일 이상'
            WHEN DATEDIFF(END_DATE, START_DATE) >= 7 THEN '7일 이상'
        END AS DURATION_TYPE
    FROM CAR_RENTAL_COMPANY_RENTAL_HISTORY CRCRH
    JOIN CAR_RENTAL_COMPANY_CAR CRCC ON CRCRH.CAR_ID = CRCC.CAR_ID
    WHERE CRCC.CAR_TYPE = '트럭')
SELECT
    HISTORY_ID,
    DAILY_FEE * DURATION * (100 - IFNULL(CRCDP.DISCOUNT_RATE, 0)) / 100 AS FEE
FROM TRUCK_TABLE TT
LEFT JOIN CAR_RENTAL_COMPANY_DISCOUNT_PLAN CRCDP ON TT.CAR_TYPE = CRCDP.CAR_TYPE
                                            AND TT.DURATION_TYPE = CRCDP.DURATION_TYPE
ORDER BY FEE DESC, HISTORY_ID DESC
;