SELECT
    FP.PRODUCT_ID,
    FP.PRODUCT_NAME,
    SUM(T.AMOUNT * FP.PRICE) AS TOTAL_SALES
FROM FOOD_PRODUCT FP
JOIN (
        SELECT
            PRODUCT_ID,
            AMOUNT
        FROM FOOD_ORDER
        WHERE YEAR(PRODUCE_DATE) = 2022 AND MONTH(PRODUCE_DATE) = 5
    ) AS T ON FP.PRODUCT_ID = T.PRODUCT_ID 
GROUP BY FP.PRODUCT_ID
ORDER BY TOTAL_SALES DESC, FP.PRODUCT_ID ASC
;