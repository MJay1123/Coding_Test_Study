SELECT
    DISTINCT MILK_CARTS.CART_ID
FROM (
        SELECT
            CART_ID
        FROM CART_PRODUCTS
        WHERE NAME = 'Milk'
    ) AS MILK_CARTS
JOIN (
        SELECT
            CART_ID
        FROM CART_PRODUCTS
        WHERE NAME = 'Yogurt'
    ) AS YOGURT_CARTS ON MILK_CARTS.CART_ID = YOGURT_CARTS.CART_ID
ORDER BY CART_ID ASC
;
