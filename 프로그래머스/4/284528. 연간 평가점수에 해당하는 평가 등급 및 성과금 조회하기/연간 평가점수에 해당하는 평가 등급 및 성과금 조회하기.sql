SELECT
    HE.EMP_NO,
    HE.EMP_NAME,
    CASE
        WHEN(AVG(HG.SCORE) >= 96) THEN 'S'
        WHEN(AVG(HG.SCORE) >= 90) THEN 'A'
        WHEN(AVG(HG.SCORE) >= 80) THEN 'B'
        ELSE 'C'
    END AS GRADE,
    CASE
        WHEN(AVG(HG.SCORE) >= 96) THEN 0.2 * HE.SAL
        WHEN(AVG(HG.SCORE) >= 90) THEN 0.15 * HE.SAL
        WHEN(AVG(HG.SCORE) >= 80) THEN 0.1 * HE.SAL
        ELSE 0 * HE.SAL
    END AS BONUS
FROM HR_EMPLOYEES HE
JOIN HR_GRADE HG ON HE.EMP_NO = HG.EMP_NO
GROUP BY HE.EMP_NO
ORDER BY HE.EMP_NO ASC
;