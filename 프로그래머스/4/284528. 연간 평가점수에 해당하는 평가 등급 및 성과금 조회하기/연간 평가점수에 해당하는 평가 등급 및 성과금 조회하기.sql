SELECT
    EMP_NO,
    EMP_NAME,
    CASE
        WHEN SCORE >= 96 THEN 'S'
        WHEN SCORE >= 90 THEN 'A'
        WHEN SCORE >= 80 THEN 'B'
        ELSE 'C'
    END AS GRADE,
    CASE
        WHEN SCORE >= 96 THEN 0.2 * SAL
        WHEN SCORE >= 90 THEN 0.15 * SAL
        WHEN SCORE >= 80 THEN 0.1 * SAL
        ELSE 0
    END AS BONUS
FROM (SELECT
        HE.EMP_NO,
        HE.EMP_NAME,
        AVG(HG.SCORE) AS SCORE,
        HE.SAL
      FROM HR_EMPLOYEES HE
      JOIN HR_DEPARTMENT HD ON HE.DEPT_ID = HD.DEPT_ID
      JOIN HR_GRADE HG ON HE.EMP_NO = HG.EMP_NO
      GROUP BY HE.EMP_NO) HEHG
;