SELECT
    FR.ID,
    FR.FISH_NAME,
    FR.LENGTH
FROM (SELECT
        FI.ID,
        FI.FISH_TYPE,
        FNI.FISH_NAME,
        FI.LENGTH,
        RANK() OVER(PARTITION BY FI.FISH_TYPE ORDER BY FI.LENGTH DESC) AS `RANK`
      FROM FISH_INFO FI
      JOIN FISH_NAME_INFO FNI ON FI.FISH_TYPE = FNI.FISH_TYPE
     ) AS FR
WHERE `RANK` = 1
ORDER BY FR.ID ASC
;