SELECT
    CONCAT('/home/grep/src/', BOARD_ID, '/', FILE_ID, FILE_NAME, FILE_EXT) AS FILE_PATH
FROM (SELECT
        UGB.BOARD_ID,
        UGB.WRITER_ID,
        UGB.TITLE,
        UGB.VIEWS,
        UGF.FILE_ID,
        UGF.FILE_NAME,
        UGF.FILE_EXT,
        RANK() OVER(ORDER BY UGB.VIEWS DESC) AS RNK
    FROM USED_GOODS_BOARD UGB
    JOIN USED_GOODS_FILE UGF ON UGB.BOARD_ID = UGF.BOARD_ID) AS RANK_TABLE
WHERE RANK_TABLE.RNK = 1
ORDER BY RANK_TABLE.FILE_ID DESC
;